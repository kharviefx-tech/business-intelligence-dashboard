function ThemeBoot() {
  useEffect(() => {
    const saved = window.localStorage.getItem("meridian.theme");
    const dark = saved ? saved === "dark" : window.matchMedia("(prefers-color-scheme: dark)").matches;
    document.documentElement.classList.toggle("dark", dark);
  }, []);
  return null;
}

function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en" suppressHydrationWarning>
      <head>
        <HeadContent />
        <script
          dangerouslySetInnerHTML={{
            __html: `(function(){try{var s=localStorage.getItem('meridian.theme');var d=s?s==='dark':window.matchMedia('(prefers-color-scheme: dark)').matches;if(d)document.documentElement.classList.add('dark');}catch(e){}})();`,
          }}
        />
      </head>
      <body suppressHydrationWarning>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const [client] = useState(() => queryClient);

  return (
    <QueryClientProvider client={client}>
      <ThemeBoot />
      <Outlet />
      {/* Mounted here so `toast()` from "sonner" works anywhere in the app. */}
      <Toaster position="bottom-center" />
    </QueryClientProvider>
  );
}
